function detect(): Lang {
  const q = new URLSearchParams(location.search).get('lang') as Lang | null;
  if (q && q in dict) {
    localStorage.setItem('sansa.lang', q);
    return q;
  }
  const saved = localStorage.getItem('sansa.lang') as Lang | null;
  if (saved && saved in dict) return saved;
  const nav = (navigator.language || 'en').toLowerCase();
  if (nav.startsWith('zh')) return 'zh';
  if (nav.startsWith('ko')) return 'ko';
  if (nav.startsWith('ja')) return 'ja';
  return 'en';
}

let lang: Lang = detect();
const listeners = new Set<() => void>();

export function getLang() {
  return lang;
}

export function setLang(l: Lang) {
  lang = l;
  localStorage.setItem('sansa.lang', l);
  document.documentElement.lang = l === 'zh' ? 'zh-CN' : l;
  listeners.forEach((fn) => fn());
}

export function onLangChange(fn: () => void) {
  listeners.add(fn);
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s: string = dict[lang][key] ?? dict.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function randomName(l: Lang = lang): string {
  const [a, b, sep] = NAME_PARTS[l];
  return a[Math.floor(Math.random() * a.length)] + sep + b[Math.floor(Math.random() * b.length)];
}

export const LANG_LABELS: Record<Lang, string> = { zh: '简体中文', ko: '한국어', ja: '日本語', en: 'English' };

document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
